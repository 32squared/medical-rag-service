def apply(text, pairs, label):
    n = 0
    for old, new in pairs:
        if new in text and old not in text:
            continue  # 이미 적용
        c = text.count(old)
        if c != 1:
            raise SystemExit('[%s] 원문 매칭 %d회 (1회여야 함): %s' % (label, c, old[:60].replace('\n', ' ')))
        text = text.replace(old, new); n += 1
    return text, n


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    repo = sys.argv[1]
    dry = sys.argv[sys.argv.index('--dry-run') + 1] if '--dry-run' in sys.argv else None
    targets = {'rag_engine.py': R_ENGINE + R_ENGINE_RAW, 'personal_llm_context.py': R_PLC}
    for fn, pairs in targets.items():
        src = os.path.join(repo, fn)
        text = open(src, encoding='utf-8').read()
        new_text, n = apply(text, pairs, fn)
        dst = os.path.join(dry, fn) if dry else src
        if dry:
            os.makedirs(dry, exist_ok=True)
        if n == 0:
            print(fn, ': 이미 적용됨 (변경 없음)')
            if dry:
                shutil.copyfile(src, dst)
            continue
        open(dst, 'w', encoding='utf-8', newline='\n').write(new_text)
        py_compile.compile(dst, doraise=True)
        print(fn, ': 치환 %d건 적용 -> %s (컴파일 OK)' % (n, dst))
    print('marker present:', MARK in open(os.path.join(dry or repo, 'rag_engine.py'), encoding='utf-8').read())


if __name__ == '__main__':
    main()
