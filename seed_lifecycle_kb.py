def build_lifecycle_documents(defs: List[Dict] = None) -> List[Dict]:
    """생애주기 정의 → ingest 문서 dict 리스트 (순수 함수)."""
    defs = defs if defs is not None else _DOCS_DEF
    docs: List[Dict] = []
    for d in defs:
        title = d.get("title", "")
        if not title:
            continue
        content_md = f"# {title}\n\n{d.get('content', '')}"
        docs.append({
            "title": title,
            "content_md": content_md,
            "source_id": _SOURCE_ID,
            # 문서별 고유 URL(앵커) — 같은 출처 다수 문서가 source_url을 공유해
            # ingest 멱등성 체크(title OR source_url)에서 서로 덮어쓰는 문제 방지
            "source_url": (f"{d.get('url','')}#{d.get('key','')}" if d.get("url") else ""),
            "metadata": {
                "evidence_level": "B",
                "source_priority": 2,
                "chunk_type": "patient_info",
                "doc_key": d.get("key", ""),
            },
            "evidence_topic": d.get("topic", "general"),
            "regulatory_korea": True,
            "topic_keywords": d.get("keywords", []),
        })
    return docs


def _register_source() -> None:
    from kb_ingest import seed_kb_sources
    seed_kb_sources([_LIFECYCLE_SOURCE])
    try:
        from dbcommon import get_conn, _p
        with get_conn() as (conn, cur):
            cur.execute(
                f"UPDATE kb_sources SET priority_rank = 2, jurisdiction = 'KR', "
                f"institution = '공공기관 건강정보 큐레이션' WHERE id = {_p()}",
                (_SOURCE_ID,),
            )
    except Exception as e:
        print(f"[seed_lifecycle] priority_rank 보강 생략: {str(e)[:80]}", flush=True)


def seed_lifecycle_kb(dry_run: bool = False) -> Dict:
    docs = build_lifecycle_documents()
    summary = {"documents": len(docs), "ingested": 0}
    if dry_run:
        summary["dry_run"] = True
        return summary

    _register_source()
    import kb_ingest
    for d in docs:
        try:
            kb_ingest.ingest_document(
                title=d["title"], content_md=d["content_md"], source_id=d["source_id"],
                metadata=d["metadata"], evidence_country="KR",
                evidence_topic=d["evidence_topic"], regulatory_korea=d["regulatory_korea"],
                topic_keywords=d["topic_keywords"], source_url=d.get("source_url", ""),
                upsert=True, status="active",
            )
            summary["ingested"] += 1
        except Exception as e:
            print(f"[seed_lifecycle] ingest 실패 {d['title']}: {str(e)[:100]}", flush=True)
    return summary


def main():
    ap = argparse.ArgumentParser(description="질환·생애주기 건강정보 → KB 적재")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    s = seed_lifecycle_kb(dry_run=args.dry_run)
    print(f"[seed_lifecycle] 결과: {s}", flush=True)


if __name__ == "__main__":
    main()
